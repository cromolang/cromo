// Memory functions for ARM64 on Linux (D19, D405), assembled with the assembler
// integrated in LLVM, as mem_x64.S. LLVM can emit calls to these functions even
// when the program does not use them, so the runtime must always provide them.
// The arguments arrive in x0 to x7, and x0 to x18 can be changed.
//
// The file also has the entry point _start, the switch of the tasks, the return
// of the handlers of the signals, and the functions that LLVM calls for the
// atomic operations (D407).

    .arch armv8-a+lse
    .text

// void cromo_pause(void): the hint of a loop that waits for another thread.
    .globl cromo_pause
    .p2align 4
cromo_pause:
    yield
    ret

// void* memcpy(void* dest, const void* src, size_t count): 16 bytes at a time,
// then the rest one byte at a time.
    .globl memcpy
    .p2align 4
memcpy:
    mov x3, x0
1:  cmp x2, #16
    b.lo 2f
    ldp x4, x5, [x1], #16
    stp x4, x5, [x3], #16
    sub x2, x2, #16
    b 1b
2:  cbz x2, 3f
    ldrb w4, [x1], #1
    strb w4, [x3], #1
    sub x2, x2, #1
    b 2b
3:  ret

// void* memset(void* dest, int value, size_t count): the byte in all the eight of
// a register, then as memcpy.
    .globl memset
    .p2align 4
memset:
    mov x3, x0
    and w1, w1, #0xff
    orr w1, w1, w1, lsl #8
    orr w1, w1, w1, lsl #16
    orr x1, x1, x1, lsl #32
1:  cmp x2, #16
    b.lo 2f
    stp x1, x1, [x3], #16
    sub x2, x2, #16
    b 1b
2:  cbz x2, 3f
    strb w1, [x3], #1
    sub x2, x2, #1
    b 2b
3:  ret

// void* memmove(void* dest, const void* src, size_t count): copies backwards when
// the destination overlaps the end of the source, forwards with memcpy otherwise.
    .globl memmove
    .p2align 4
memmove:
    sub x3, x0, x1
    cmp x3, x2
    b.hs memcpy
    add x1, x1, x2
    add x3, x0, x2
1:  cmp x2, #16
    b.lo 2f
    ldp x4, x5, [x1, #-16]!
    stp x4, x5, [x3, #-16]!
    sub x2, x2, #16
    b 1b
2:  cbz x2, 3f
    ldrb w4, [x1, #-1]!
    strb w4, [x3, #-1]!
    sub x2, x2, #1
    b 2b
3:  ret

// int memcmp(const void* a, const void* b, size_t count), 8 bytes at a time, as on
// x86-64; LLVM calls bcmp when it only needs to know whether the bytes are equal.
// Two words that differ are compared as big-endian numbers: their first byte that
// differs decides.
    .globl memcmp
    .globl bcmp
    .p2align 4
memcmp:
bcmp:
1:  cmp x2, #8
    b.lo 3f
    ldr x3, [x0], #8
    ldr x4, [x1], #8
    cmp x3, x4
    b.ne 2f
    sub x2, x2, #8
    b 1b
2:  rev x3, x3
    rev x4, x4
    cmp x3, x4
    cset w0, hi
    csinv w0, w0, wzr, hs
    ret
3:  cbz x2, 5f
    ldrb w3, [x0], #1
    ldrb w4, [x1], #1
    subs w3, w3, w4
    b.ne 4f
    sub x2, x2, #1
    b 3b
4:  mov w0, w3
    ret
5:  mov w0, #0
    ret

// _start: the kernel enters here with the stack aligned to 16 bytes. The stack
// holds the number of arguments and their addresses, which the runtime reads from
// cromo_initial_stack. cromo_start, generated by the compiler, never returns.
//
// The register tpidr_el0 of every thread points to its block in the runtime,
// which says whether it is a worker of the tasks (D269): for the main thread, it
// is set here, before anything else. With Bionic (P43) the register is that of
// Bionic, and _start gives the stack to cromo_bionic_start of runtime/bionic.c, as
// crtbegin_dynamic.o of the NDK.
    .globl _start
    .p2align 4
_start:
    mov x29, #0
    mov x30, #0
    mov x0, sp
    adrp x1, cromo_initial_stack
    str x0, [x1, :lo12:cromo_initial_stack]
#ifdef CROMO_BIONIC
    bl cromo_bionic_start
#else
    adrp x0, cromo_main_block
    add x0, x0, :lo12:cromo_main_block
    msr tpidr_el0, x0
    bl cromo_start
#endif
    brk #0

// void cromo_switch(void** save, void* next): leaves the stack of the caller,
// keeping its stack pointer in *save, and continues on the stack `next` where
// another cromo_switch left it (D269). The registers that a call preserves, x19
// to x30 and d8 to d15, and the control register of the floating point stay on
// each stack, in this order: startFrame (cromo_rt.c) writes the first one.
    .globl cromo_switch
    .p2align 4
cromo_switch:
    sub sp, sp, #176
    stp x19, x20, [sp, #0]
    stp x21, x22, [sp, #16]
    stp x23, x24, [sp, #32]
    stp x25, x26, [sp, #48]
    stp x27, x28, [sp, #64]
    stp x29, x30, [sp, #80]
    stp d8, d9, [sp, #96]
    stp d10, d11, [sp, #112]
    stp d12, d13, [sp, #128]
    stp d14, d15, [sp, #144]
    mrs x9, fpcr
    str x9, [sp, #160]
    mov x9, sp
    str x9, [x0]
    mov sp, x1
    ldr x9, [sp, #160]
    msr fpcr, x9
    ldp x19, x20, [sp, #0]
    ldp x21, x22, [sp, #16]
    ldp x23, x24, [sp, #32]
    ldp x25, x26, [sp, #48]
    ldp x27, x28, [sp, #64]
    ldp x29, x30, [sp, #80]
    ldp d8, d9, [sp, #96]
    ldp d10, d11, [sp, #112]
    ldp d12, d13, [sp, #128]
    ldp d14, d15, [sp, #144]
    add sp, sp, #176
    ret

// Where a new stack of a task starts: its first cromo_switch returns here, with
// the stack in x19 and the stack pointer aligned to 16 bytes.
    .globl cromo_task_entry
    .p2align 4
cromo_task_entry:
    mov x0, x19
    bl cromo_task_run
    brk #0

// The return of a handler of a signal, rt_sigreturn, given to rt_sigaction as
// SA_RESTORER, as on x86-64 (D339).
    .globl cromo_sigreturn
    .p2align 4
cromo_sigreturn:
    mov x8, #139
    svc #0
    brk #0

// ---- The atomics (D407) ----
//
// __aarch64_<operation><size>_<order>, as libgcc and compiler-rt name them, which
// LLVM calls with +outline-atomics. With the atomics of ARMv8.1, which the runtime
// finds at the start (cromo_lse_atomics), each is one instruction; without them, a
// loop of the exclusive load and store of ARMv8.0. `a` is the acquire of the load
// and `l` the release of the store, empty for relax; `s` is the suffix of the
// size, and `r` its registers, w or x.

.macro LSE_CHECK
    adrp x16, cromo_lse_atomics
    ldrb w16, [x16, :lo12:cromo_lse_atomics]
.endm

// cas: x0 the expected value, x1 the new one, x2 the address; x0 the old value.
// `ext` takes the expected value without the bits above its size.
.macro CAS size, s, r, ext, order, a, l
    .globl __aarch64_cas\size\()_\order
    .p2align 4
__aarch64_cas\size\()_\order:
    LSE_CHECK
    cbz w16, 1f
    cas\a\l\s \r\()0, \r\()1, [x2]
    ret
1:  \ext \r\()16, \r\()0
2:  ld\a\()xr\s \r\()0, [x2]
    cmp \r\()0, \r\()16
    b.ne 3f
    st\l\()xr\s w17, \r\()1, [x2]
    cbnz w17, 2b
3:  ret
.endm

// swp: x0 the new value, x1 the address; x0 the old value.
.macro SWP size, s, r, order, a, l
    .globl __aarch64_swp\size\()_\order
    .p2align 4
__aarch64_swp\size\()_\order:
    LSE_CHECK
    cbz w16, 1f
    swp\a\l\s \r\()0, \r\()0, [x1]
    ret
1:  mov \r\()16, \r\()0
2:  ld\a\()xr\s \r\()0, [x1]
    st\l\()xr\s w17, \r\()16, [x1]
    cbnz w17, 2b
    ret
.endm

// ldadd, ldclr, ldeor and ldset: x0 the operand, x1 the address; x0 the old
// value. `inst` is the instruction of the loop: add, bic, eor or orr.
.macro LDOP op, inst, size, s, r, order, a, l
    .globl __aarch64_ld\op\size\()_\order
    .p2align 4
__aarch64_ld\op\size\()_\order:
    LSE_CHECK
    cbz w16, 1f
    ld\op\a\l\s \r\()0, \r\()0, [x1]
    ret
1:  mov \r\()16, \r\()0
2:  ld\a\()xr\s \r\()0, [x1]
    \inst \r\()17, \r\()0, \r\()16
    st\l\()xr\s w15, \r\()17, [x1]
    cbnz w15, 2b
    ret
.endm

.macro LDOPS op, inst, order, a, l
    LDOP \op, \inst, 1, b, w, \order, \a, \l
    LDOP \op, \inst, 2, h, w, \order, \a, \l
    LDOP \op, \inst, 4, , w, \order, \a, \l
    LDOP \op, \inst, 8, , x, \order, \a, \l
.endm

.macro ATOMICS order, a, l
    CAS 1, b, w, uxtb, \order, \a, \l
    CAS 2, h, w, uxth, \order, \a, \l
    CAS 4, , w, mov, \order, \a, \l
    CAS 8, , x, mov, \order, \a, \l
    SWP 1, b, w, \order, \a, \l
    SWP 2, h, w, \order, \a, \l
    SWP 4, , w, \order, \a, \l
    SWP 8, , x, \order, \a, \l
    LDOPS add, add, \order, \a, \l
    LDOPS clr, bic, \order, \a, \l
    LDOPS eor, eor, \order, \a, \l
    LDOPS set, orr, \order, \a, \l
.endm

    ATOMICS relax, ,
    ATOMICS acq, a,
    ATOMICS rel, , l
    ATOMICS acq_rel, a, l

    .section .note.GNU-stack, "", %progbits
