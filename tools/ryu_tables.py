# Writes runtime/ryu_tables.h: the powers of 5 for the shortest digits of an f64
# with Ryu (Ulf Adams, "Ryu: fast float-to-string conversion", PLDI 2018), each in
# 125 bits as two words, the low one first. Run it from the folder of the project:
#   python tools/ryu_tables.py
import os

BITS = 125
POW5 = 326      # 5^i shifted to 125 bits, for the negative exponents of 2
POW5_INV = 342  # 2^(len(5^i) - 1 + 125) / 5^i + 1, for the positive ones


def words(value):
    return '{%#018xull, %#018xull}' % (value & (2**64 - 1), value >> 64)


def table(name, values):
    lines = ['static const u64 %s[%d][2] = {' % (name, len(values))]
    for value in values:
        lines.append('    %s,' % words(value))
    lines.append('};')
    return '\n'.join(lines)


split = []
for i in range(POW5):
    power = 5 ** i
    shift = power.bit_length() - BITS
    split.append(power >> shift if shift >= 0 else power << -shift)

inverse = []
for i in range(POW5_INV):
    power = 5 ** i
    inverse.append((1 << (power.bit_length() - 1 + BITS)) // power + 1)

text = '''// Generated by tools/ryu_tables.py: the powers of 5 of Ryu for the f64 (D63).

''' + table('ryuPow5', split) + '\n\n' + table('ryuPow5Inverse', inverse) + '\n'
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'runtime', 'ryu_tables.h')
with open(path, 'w', newline='\n') as out:
    out.write(text)
print('wrote', os.path.normpath(path))
