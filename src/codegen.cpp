#include "codegen.h"

#include "sema.h"

#include <sstream>

namespace cromo {

namespace {

std::string llvmType(const TypeName& type) {
    if (type.name == "void") return "void";
    return "i" + std::to_string(findIntType(type.name)->bits);
}

// Writes the constant as a signed integer of the type's width, as LLVM expects:
// for example 255 in a u8 becomes -1.
std::string llvmConstant(const ConstInt& value, int bits) {
    uint64_t pattern = value.negative ? ~value.magnitude + 1 : value.magnitude;
    if (bits < 64) {
        uint64_t mask = (uint64_t{1} << bits) - 1;
        pattern &= mask;
        if (pattern & (uint64_t{1} << (bits - 1))) {
            return "-" + std::to_string((~pattern + 1) & mask);
        }
        return std::to_string(pattern);
    }
    if (pattern & (uint64_t{1} << 63)) return "-" + std::to_string(~pattern + 1);
    return std::to_string(pattern);
}

// Strings in the IR go between quotes, with special characters in hexadecimal.
std::string quoted(const std::string& text) {
    std::string out = "\"";
    for (unsigned char c : text) {
        if (c == '"' || c == '\\' || c < 0x20 || c >= 0x7F) {
            const char* hex = "0123456789ABCDEF";
            out += '\\';
            out += hex[c >> 4];
            out += hex[c & 0xF];
        } else {
            out += static_cast<char>(c);
        }
    }
    return out + "\"";
}

void emitFunction(std::ostringstream& out, const FunctionDecl& function) {
    std::string type = llvmType(function.returnType);
    out << "define " << type << " @" << function.name << "() nounwind {\n";
    out << "entry:\n";
    for (const auto& statement : function.body.statements) {
        if (statement->kind == StmtKind::Return) {
            const auto& ret = static_cast<const ReturnStmt&>(*statement);
            if (ret.value) {
                int bits = findIntType(function.returnType.name)->bits;
                out << "  ret " << type << " " << llvmConstant(evaluateConstant(*ret.value), bits) << "\n";
            } else {
                out << "  ret void\n";
            }
            out << "}\n\n";
            return;  // what follows is unreachable (sema has already reported it)
        }
    }
    out << "  ret void\n";  // void function without a final ret (D47)
    out << "}\n\n";
}

}  // namespace

std::string generateIR(const Module& module, const std::string& sourceName) {
    std::ostringstream out;
    out << "; Generated by cromo\n";
    out << "source_filename = " << quoted(sourceName) << "\n";
    out << "target triple = \"" << kTargetTriple << "\"\n\n";

    const FunctionDecl* mainFunction = nullptr;
    for (const FunctionDecl& function : module.functions) {
        emitFunction(out, function);
        if (function.name == "main") mainFunction = &function;
    }

    if (mainFunction) {
        bool returnsCode = mainFunction->returnType.name != "void";
        out << "declare dllimport void @ExitProcess(i32) noreturn nounwind\n\n";
        out << "define void @cromo_start() noreturn nounwind {\n";
        out << "entry:\n";
        if (returnsCode) {
            out << "  %code = call i32 @main()\n";
            out << "  call void @ExitProcess(i32 %code)\n";
        } else {
            out << "  call void @main()\n";
            out << "  call void @ExitProcess(i32 0)\n";
        }
        out << "  unreachable\n";
        out << "}\n";
    }
    return out.str();
}

}  // namespace cromo
